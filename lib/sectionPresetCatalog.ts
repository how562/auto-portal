export function getPresetsByCategory(
  category: PresetLibraryCategory,
): SectionPresetCatalogEntry[] {
  return SECTION_PRESET_CATALOG.filter((p) => p.library_category === category);
}

export function getPickerVisiblePresets(): SectionPresetCatalogEntry[] {
  return SECTION_PRESET_CATALOG.filter(
    (p) => p.library_visibility === "promoted" || p.library_visibility === "standard",
  );
}

export function getCatalogCategoryCounts(): Record<PresetLibraryCategory, number> {
  const counts = {} as Record<PresetLibraryCategory, number>;
  for (const cat of PRESET_LIBRARY_CATEGORIES) {
    counts[cat.id] = SECTION_PRESET_CATALOG.filter(
      (p) => p.library_category === cat.id,
    ).length;
  }
  return counts;
}

