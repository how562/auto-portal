const R_SHOWCASE: PresetReadiness = {
  showcase_preview: true,
  page_builder_starter: false,
  admin_field_schema: false,
  image_size_guidance: true,
  responsive_layout: true,
  mobile_admin_preview: false,
};

const R_STARTER: PresetReadiness = {
  ...R_SHOWCASE,
  page_builder_starter: true,
  admin_field_schema: true,
};

function e(
  partial: Omit<SectionPresetCatalogEntry, "readiness"> & {
    readiness?: Partial<PresetReadiness>;
  },
): SectionPresetCatalogEntry {
  const base = partial.maps_to_library_type
    ? { ...R_SHOWCASE, ...partial.readiness }
    : { ...R_SHOWCASE, ...partial.readiness };
  if (
    partial.maps_to_library_type &&
    ["hero", "text_block", "image_text", "cta_band", "card_grid", "faq", "stats", "form", "locations", "split_feature"].includes(
      partial.maps_to_library_type,
    )
  ) {
    return {
      ...partial,
      readiness: {
        ...R_STARTER,
        mobile_admin_preview: false,
        ...partial.readiness,
      },
    };
  }
  return { ...partial, readiness: base };
}

